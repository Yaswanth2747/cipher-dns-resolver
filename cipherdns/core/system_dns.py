"""
cipherDNS System DNS Controller
Manages automatic routing of system-wide operating system DNS traffic (Chrome, curl, wget)
to cipherDNS (127.0.0.1:53), with clean automatic restoration.
"""

import os
import shutil
import subprocess
from typing import Dict, Any, Optional

BACKUP_RESOLV_CONF = "/etc/resolv.conf.cipherdns.bak"
RESOLV_CONF = "/etc/resolv.conf"


def get_default_interface() -> str:
    """Finds the default routing network interface."""
    try:
        proc = subprocess.run(
            ["ip", "route"], capture_output=True, text=True, timeout=3
        )
        for line in proc.stdout.splitlines():
            if line.startswith("default"):
                parts = line.split()
                if "dev" in parts:
                    idx = parts.index("dev")
                    if idx + 1 < len(parts):
                        return parts[idx + 1]
    except Exception:
        pass
    return "enp2s0"


def get_system_dns_status() -> Dict[str, Any]:
    """Checks whether the system DNS is currently routed to cipherDNS (127.0.0.1)."""
    iface = get_default_interface()
    is_routed = False
    active_servers = []

    # Check resolvectl status
    try:
        proc = subprocess.run(
            ["resolvectl", "status", iface],
            capture_output=True,
            text=True,
            timeout=3,
        )
        for line in proc.stdout.splitlines():
            if "DNS Servers:" in line or "Current DNS Server:" in line:
                servers = line.split(":", 1)[1].strip().split()
                active_servers.extend(servers)
    except Exception:
        pass

    # Check /etc/resolv.conf
    try:
        if os.path.exists(RESOLV_CONF):
            with open(RESOLV_CONF, "r") as f:
                for line in f:
                    if line.strip().startswith("nameserver"):
                        ns = line.split()[1]
                        if ns not in active_servers:
                            active_servers.append(ns)
    except Exception:
        pass

    if "127.0.0.1" in active_servers:
        is_routed = True

    return {
        "interface": iface,
        "is_routed_to_cipherdns": is_routed,
        "servers": active_servers,
    }


def enable_system_dns(dns_ip: str = "127.0.0.1") -> Dict[str, Any]:
    """
    Directs all system DNS traffic (Chrome, curl, wget, etc.) to cipherDNS.
    1. Directs resolvectl interface DNS to 127.0.0.1 and flushes caches.
    2. If root, backs up /etc/resolv.conf and points nameserver to 127.0.0.1.
    """
    iface = get_default_interface()
    results = []

    # 1. Update resolvectl
    try:
        subprocess.run(["resolvectl", "dns", iface, dns_ip], check=True, timeout=4)
        subprocess.run(["resolvectl", "flush-caches"], check=True, timeout=4)
        results.append(f"resolvectl set {iface} -> {dns_ip}")
    except Exception as e:
        results.append(f"resolvectl failed: {e}")

    # 2. Update /etc/resolv.conf directly if running with write permissions
    try:
        if os.access(RESOLV_CONF, os.W_OK) or os.geteuid() == 0:
            if not os.path.exists(BACKUP_RESOLV_CONF):
                if os.path.islink(RESOLV_CONF):
                    # Save symlink destination
                    target = os.readlink(RESOLV_CONF)
                    with open(BACKUP_RESOLV_CONF, "w") as bf:
                        bf.write(f"SYMLINK:{target}\n")
                else:
                    shutil.copy2(RESOLV_CONF, BACKUP_RESOLV_CONF)

            # Write direct nameserver entry
            # Remove existing file/symlink first so we write cleanly
            try:
                os.remove(RESOLV_CONF)
            except Exception:
                pass
            with open(RESOLV_CONF, "w") as f:
                f.write(
                    "# Generated by cipherDNS\n"
                    "nameserver 127.0.0.1\n"
                    "options edns0 trust-ad\n"
                )
            results.append("Updated /etc/resolv.conf to nameserver 127.0.0.1")
    except Exception as e:
        results.append(f"/etc/resolv.conf update skipped: {e}")

    return {
        "success": True,
        "interface": iface,
        "actions": results,
        "status": get_system_dns_status(),
    }


def disable_system_dns(fallback_dns: str = "10.200.1.11") -> Dict[str, Any]:
    """
    Restores original system DNS configuration.
    """
    iface = get_default_interface()
    results = []

    # 1. Restore resolvectl
    try:
        try:
            subprocess.run(["resolvectl", "revert", iface], check=True, timeout=4)
            results.append(f"resolvectl reverted {iface}")
        except Exception:
            subprocess.run(["resolvectl", "dns", iface, fallback_dns], check=True, timeout=4)
            results.append(f"resolvectl reset {iface} -> {fallback_dns}")
        subprocess.run(["resolvectl", "flush-caches"], check=True, timeout=4)
    except Exception as e:
        results.append(f"resolvectl revert failed: {e}")

    # 2. Restore /etc/resolv.conf
    try:
        if os.path.exists(BACKUP_RESOLV_CONF):
            with open(BACKUP_RESOLV_CONF, "r") as bf:
                first_line = bf.readline()

            if first_line.startswith("SYMLINK:"):
                target = first_line.split(":", 1)[1].strip()
                try:
                    os.remove(RESOLV_CONF)
                except Exception:
                    pass
                os.symlink(target, RESOLV_CONF)
                results.append(f"Restored /etc/resolv.conf symlink -> {target}")
            else:
                shutil.copy2(BACKUP_RESOLV_CONF, RESOLV_CONF)
                results.append("Restored /etc/resolv.conf from backup")

            os.remove(BACKUP_RESOLV_CONF)
    except Exception as e:
        results.append(f"/etc/resolv.conf restore failed: {e}")

    return {
        "success": True,
        "interface": iface,
        "actions": results,
        "status": get_system_dns_status(),
    }
