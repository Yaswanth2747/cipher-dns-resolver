#!/usr/bin/env bash
# cipherDNS System DNS Setup Script
# Redirects local OS DNS resolution to 127.0.0.1 for Chrome, curl, wget, etc.

set -e

INTERFACE=$(ip route | grep default | awk '{print $5}' | head -n1)
INTERFACE=${INTERFACE:-enp2s0}

echo "[cipherDNS] Directing system DNS on $INTERFACE to 127.0.0.1..."

# 1. Update resolvectl
if command -v resolvectl &> /dev/null; then
    resolvectl dns "$INTERFACE" 127.0.0.1 2>/dev/null || true
    resolvectl flush-caches 2>/dev/null || true
fi

# 2. Update /etc/resolv.conf directly
if [ "$EUID" -eq 0 ]; then
    if [ ! -f /etc/resolv.conf.cipherdns.bak ]; then
        if [ -L /etc/resolv.conf ]; then
            TARGET=$(readlink /etc/resolv.conf)
            echo "SYMLINK:$TARGET" > /etc/resolv.conf.cipherdns.bak
        else
            cp -a /etc/resolv.conf /etc/resolv.conf.cipherdns.bak
        fi
    fi
    rm -f /etc/resolv.conf
    cat << 'EOF' > /etc/resolv.conf
# Generated by cipherDNS
nameserver 127.0.0.1
options edns0 trust-ad
EOF
    echo "[cipherDNS] /etc/resolv.conf updated to 127.0.0.1"
else
    echo "[!] To also update /etc/resolv.conf for direct glibc queries, run:"
    echo "    sudo bash -c 'echo nameserver 127.0.0.1 > /etc/resolv.conf'"
fi

echo "[cipherDNS] All laptop traffic is now directed to cipherDNS!"
echo "[cipherDNS] Try in any terminal: curl -I https://wikipedia.org"
